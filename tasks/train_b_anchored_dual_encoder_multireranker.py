"""Nested-cross-fit the B-anchored dual-encoder/multi-reranker integration.

For every outer formula fold, both the parent A/B chain and the incremental
residual exclude that fold.  Parent scores used to train the incremental head
are generated by an inner formula cross-fit inside the outer training set.
Consequently, an outer-fold label cannot reach the second-stage fit through a
different row's nominally OOF parent score.

New evidence enters only as a bounded residual relative to the closest
already-counted family member:

* Stage-1 and Phase-A are separate contrasts to Noise V1;
* MSG and historical RRF are separate contrasts to frozen P2b-on-Noise.

This makes all assets runnable without treating correlated scores as repeated
independent votes.  The no-V2 comparison is independently refitted on nested A
anchors; it is not an anchor-swap replay.  GNPS is development/consumed; this
program never reads an external benchmark.
"""
